"""Regenerate entity-index.md from the frontmatter of every bible file.

usage (from the repo root): python3 tools/build_index.py
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKIP_TYPES = {"section", "template"}
TYPE_ORDER = ["pc", "npc", "item", "session", "lore", "prep", "meta"]
TYPE_TITLES = {"pc": "Player characters", "npc": "NPCs", "item": "Items",
               "session": "Sessions", "lore": "Lore", "prep": "Prep (current & archived)",
               "meta": "Reference"}


def frontmatter(path):
    text = open(path, encoding="utf-8").read()
    if not text.startswith("---\n"):
        return None
    block = text[4:text.index("\n---\n", 4)]
    meta = {}
    for line in block.split("\n"):
        key, _, val = line.partition(":")
        val = val.strip()
        if val.startswith("["):
            val = [v.strip().strip('"') for v in val[1:-1].split('",')]
            val = [v.strip('"') for v in val if v]
        else:
            val = val.strip('"').replace('\\"', '"')
        meta[key.strip()] = val
    return meta


rows = []
for path in sorted(glob.glob(os.path.join(ROOT, "**", "*.md"), recursive=True)):
    rel = os.path.relpath(path, ROOT)
    if rel.startswith(("tools/", "_")) or rel in ("README.md", "entity-index.md", "index.md"):
        continue
    meta = frontmatter(path)
    if not meta or meta.get("type") in SKIP_TYPES:
        continue
    rows.append((meta, rel))

out = ["---", 'title: "Entity index"', 'type: "meta"', "nav_order: 1", "---", "",
       "# Entity index", "",
       "*Generated by `tools/build_index.py`. Don't edit by hand; rerun the script.*", "",
       "Status: **canon** = confirmed in play; **idea** = GM ideation, `[IDEA — NONCANONICAL]`; "
       "**mixed** = canonical entry with some tagged ideation inside.", ""]


def cell(s):
    return str(s).replace("|", "\\|")


for t in TYPE_ORDER:
    group = [(m, r) for m, r in rows if m.get("type") == t]
    if not group:
        continue
    if t == "session":
        group.sort(key=lambda mr: float(mr[0].get("session", 0)))
    out += [f"## {TYPE_TITLES[t]}", "", "| Name | Aliases | File | Status | Last session |",
            "| --- | --- | --- | --- | --- |"]
    for m, rel in group:
        aliases = ", ".join(m.get("aliases", [])) if isinstance(m.get("aliases"), list) else ""
        last = m.get("last-session", m.get("session", ""))
        out.append(f"| {cell(m.get('title', rel))} | {cell(aliases)} | [{rel}]({rel}) | "
                   f"{m.get('status', '')} | {last} |")
    out.append("")

open(os.path.join(ROOT, "entity-index.md"), "w", encoding="utf-8").write("\n".join(out))
print(f"indexed {len(rows)} files")
